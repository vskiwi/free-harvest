void hr_gfx_init(void)
{
    hr_gfx_clear(0);
}

void hr_gfx_clear(uint16_t color)
{
    const uint16_t c = swap16(color);
    for (int i = 0; i < HR_GFX_W * HR_GFX_H; i++) {
        s_fb[i] = c;
    }
}

void hr_gfx_fill_rect(int x, int y, int w, int h, uint16_t color)
{
    if (x < 0) {
        w += x;
        x = 0;
    }
    if (y < 0) {
        h += y;
        y = 0;
    }
    if (x + w > HR_GFX_W) {
        w = HR_GFX_W - x;
    }
    if (y + h > HR_GFX_H) {
        h = HR_GFX_H - y;
    }
    if (w <= 0 || h <= 0) {
        return;
    }
    const uint16_t c = swap16(color);
    for (int row = y; row < y + h; row++) {
        uint16_t *p = &s_fb[row * HR_GFX_W + x];
        for (int i = 0; i < w; i++) {
            p[i] = c;
        }
    }
}

void hr_gfx_frame(int x, int y, int w, int h, int t, uint16_t color)
{
    hr_gfx_fill_rect(x, y, w, t, color);
    hr_gfx_fill_rect(x, y + h - t, w, t, color);
    hr_gfx_fill_rect(x, y, t, h, color);
    hr_gfx_fill_rect(x + w - t, y, t, h, color);
}

static void glyph(int x, int y, unsigned char ch, int scale, uint16_t fg,
                  uint16_t bg)
{
    if (ch < 32 || ch > 127) {
        ch = '?';
    }
    const uint8_t *cols = s_font5x7[ch - 32];
    for (int cx = 0; cx < HR_GFX_FONT_W; cx++) {
        const uint8_t bits = cx < 5 ? cols[cx] : 0;
        for (int cy = 0; cy < HR_GFX_FONT_H; cy++) {
            const bool on = cy < 7 && (bits >> cy) & 1;
            hr_gfx_fill_rect(x + cx * scale, y + cy * scale, scale, scale,
                             on ? fg : bg);
        }
    }
}

int hr_gfx_text_scaled(int x, int y, const char *s, int scale, uint16_t fg,
                       uint16_t bg)
{
    if (scale < 1) {
        scale = 1;
    }
    for (; *s; s++) {
        if (x >= HR_GFX_W) {
            break;
        }
        glyph(x, y, (unsigned char)*s, scale, fg, bg);
        x += HR_GFX_FONT_W * scale;
    }
    return x;
}

int hr_gfx_text6x8(int x, int y, const char *s, uint16_t fg, uint16_t bg)
{
    return hr_gfx_text_scaled(x, y, s, 1, fg, bg);
}

int hr_gfx_text_big(int x, int y, const char *s, uint16_t fg, uint16_t bg)
{
    return hr_gfx_text_scaled(x, y, s, 2, fg, bg);
}

int hr_gfx_text_huge(int x, int y, const char *s, uint16_t fg, uint16_t bg)
{
    return hr_gfx_text_scaled(x, y, s, 3, fg, bg);
}

int hr_gfx_text_width(const char *s, int scale)
{
    return (int)strlen(s) * HR_GFX_FONT_W * (scale < 1 ? 1 : scale);
}

int hr_gfx_text_right(int x_right, int y, const char *s, int scale,
                      uint16_t fg, uint16_t bg)
{
    return hr_gfx_text_scaled(x_right - hr_gfx_text_width(s, scale), y, s,
                              scale, fg, bg);
}

void hr_gfx_progress_bar(int x, int y, int w, int h, int pct, uint16_t color)
{
    if (pct < 0) {
        pct = 0;
    }
    if (pct > 100) {
        pct = 100;
    }
    hr_gfx_fill_rect(x, y, w, h, 0);
    hr_gfx_frame(x, y, w, h, 1, color);
    const int inner = w - 4;
    if (inner > 0 && h > 4) {
        hr_gfx_fill_rect(x + 2, y + 2, inner * pct / 100, h - 4, color);
    }
}

void hr_gfx_flush_all(void)
{
    hr_display_hw_flush(0, 0, HR_GFX_W, HR_GFX_H, s_fb);
}

void hr_gfx_flush_rect(int x, int y, int w, int h)
{
    (void)x;
    (void)w;
    if (y < 0) {
        h += y;
        y = 0;
    }
    if (y + h > HR_GFX_H) {
        h = HR_GFX_H - y;
    }
    if (h <= 0) {
        return;
    }
    hr_display_hw_flush(0, y, HR_GFX_W, h, &s_fb[y * HR_GFX_W]);
}

uint32_t hr_gfx_hash_rows(int y, int h)
{
    /* FNV-1a over the band. 25 KB a second at most; nothing on this chip. */
    uint32_t hsh = 2166136261u;
    const uint8_t *p = (const uint8_t *)&s_fb[y * HR_GFX_W];
    const size_t n = (size_t)h * HR_GFX_W * 2;
    for (size_t i = 0; i < n; i++) {
        hsh ^= p[i];
        hsh *= 16777619u;
    }
    return hsh;
}
